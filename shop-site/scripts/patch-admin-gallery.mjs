import fs from 'node:fs';
const path='shop-site/public/admin/index.html';
let s=fs.readFileSync(path,'utf8');
const gallery='<script src="/admin/gallery-addon.js" defer></script>';
const payment='<script src="/admin/payment-addon.js" defer></script>';
const commerce='<script src="/admin/commerce-admin.js" defer></script>';
const advanced='<script src="/admin/commerce-advanced.js" defer></script>';
const management='<script src="/admin/management-admin.js" defer></script>';
const adminUx='<script src="/admin/admin-ux.js" defer></script>';
if(!s.includes('/admin/gallery-addon.js'))s=s.replace('</body>',gallery+'\n</body>');
if(!s.includes('/admin/payment-addon.js'))s=s.replace('</body>',payment+'\n</body>');
if(!s.includes('/admin/commerce-admin.js'))s=s.replace('</body>',commerce+'\n</body>');
if(!s.includes('/admin/commerce-advanced.js'))s=s.replace('</body>',advanced+'\n</body>');
if(!s.includes('/admin/management-admin.js'))s=s.replace('</body>',management+'\n</body>');
if(!s.includes('/admin/admin-ux.js'))s=s.replace('</body>',adminUx+'\n</body>');
if(!s.includes('/admin/gallery-addon.js'))throw new Error('gallery addon was not injected');
if(!s.includes('/admin/payment-addon.js'))throw new Error('payment addon was not injected');
if(!s.includes('/admin/commerce-admin.js'))throw new Error('commerce admin was not injected');
if(!s.includes('/admin/commerce-advanced.js'))throw new Error('advanced commerce admin was not injected');
if(!s.includes('/admin/management-admin.js'))throw new Error('management admin was not injected');
if(!s.includes('/admin/admin-ux.js'))throw new Error('admin UX addon was not injected');
fs.writeFileSync(path,s);
console.log('admin gallery, payment, commerce, management and UX addons applied');
